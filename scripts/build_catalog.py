#!/usr/bin/env python3
"""Generate the README catalog and BibTeX from one local JSON source."""
from pathlib import Path
import argparse
import collections
import json
import re

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- BEGIN CATALOG -->'
END = '<!-- END CATALOG -->'

def load_data():
    papers = json.loads((ROOT / 'data/papers.json').read_text(encoding='utf-8'))
    taxonomy = json.loads((ROOT / 'data/taxonomy.json').read_text(encoding='utf-8'))
    return papers, taxonomy

def catalog(papers, taxonomy):
    counts = collections.Counter(p['origin'] for p in papers)
    lines = [BEGIN, '<!-- Generated by scripts/build_catalog.py; edit data/papers.json. -->', '',
             f"**{len(papers)} works · {counts['survey']} from the manuscript · {counts['addition']} additions.** "
             'Initial primary-source checks: 2026-10-05 UTC. Subsequent checks are recorded per entry.', '']
    for topic in taxonomy:
        selected = [p for p in papers if p['topic'] == topic['id']]
        lines += [f'<a id="{topic["id"]}"></a>',
                  f'## {topic["stage"]}: {topic["title"]}', '',
                  topic['question'], '']
        for p in selected:
            title = p['title'].replace('[', '\\[').replace(']', '\\]')
            provenance = ('Survey §' + ', §'.join(p['survey_sections'])) if p['origin'] == 'survey' else 'Added'
            code = f" · [Code / project]({p['code_url']})" if p.get('code_url') else ''
            lines += [f"- <a id=\"{p['id']}\"></a>**[{title}]({p['url']})** "
                      f"({p['venue']}, {p['year']}). {p['annotation']} **[{provenance}]**{code}", '']
    return '\n'.join(lines + [END])

def bib_escape(text):
    # UTF-8 names are retained for modern BibTeX/Biber toolchains.
    return text.replace('&', r'\&').replace('%', r'\%').replace('_', r'\_')

def bibliography(papers):
    lines = ['% Generated by scripts/build_catalog.py from data/papers.json.',
             '% Generic records preserve the selected version without inventing pages or volumes.',
             '% See docs/citation.md for the separate companion-manuscript citation.', '']
    for p in papers:
        fields = [('author', ' and '.join(p['authors'])), ('title', '{' + p['title'] + '}'),
                  ('year', str(p['year'])), ('howpublished', p['venue']), ('url', p['url'])]
        match = re.fullmatch(r'https://arxiv\.org/abs/(.+)', p['url'])
        if match:
            fields += [('eprint', match.group(1)), ('archivePrefix', 'arXiv')]
        lines.append(f"@misc{{{p['id']},")
        for key, value in fields:
            # URLs are kept verbatim so their machine-readable targets remain valid.
            value = value if key in ('url', 'eprint') else bib_escape(value)
            lines.append(f'  {key} = {{{value}}},')
        lines += ['}', '']
    return '\n'.join(lines)

def rendered_outputs():
    papers, taxonomy = load_data()
    readme = (ROOT / 'README.md').read_text(encoding='utf-8')
    if readme.count(BEGIN) != 1 or readme.count(END) != 1:
        raise ValueError('README must contain exactly one catalog block.')
    start, stop = readme.index(BEGIN), readme.index(END) + len(END)
    readme = readme[:start] + catalog(papers, taxonomy) + readme[stop:]
    return {ROOT / 'README.md': readme, ROOT / 'references.bib': bibliography(papers)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated files are stale')
    args = parser.parse_args()
    stale = []
    for path, text in rendered_outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding='utf-8')
    if stale:
        raise SystemExit('Generated content is stale: ' + ', '.join(stale))
    print('Generated content is current.' if args.check else 'Updated README catalog and references.bib.')

if __name__ == '__main__':
    main()
